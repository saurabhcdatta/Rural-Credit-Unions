Is "Rural" Different From "Small"?
  
Background
Before that presumption can be tested, a more basic question has to be settled. Rural credit unions are small. Their median
assets over the study period were about $21 million, against $37 million for non-rural credit unions; more than half hold
under $50 million, and only one in twenty exceeds $500 million. Small financial institutions of every kind — rural, suburban,
urban — face the same arithmetic. Compliance, technology, and management are largely fixed costs spread across a smaller
base.
So when rural credit unions look different from the rest of the system, two explanations are available, and they are not easy
to tell apart. Either something about operating in a rural place shapes performance, or "rural" is simply standing in for
"small,
" and what we are observing is the economics of scale wearing a geographic label.

If rural institutions are struggling because they are small, the answer concerns scale: shared services, cooperative arrangements, tailored
compliance, the cost structures of small depositories generally. If rurality itself matters, the answer concerns place: field-of-
  membership rules, capital access, formation of new charters in thin markets. Recommending the first remedy for the second
problem would waste the opportunity the statute creates.

The natural first step is to compare rural credit unions to all other credit unions. That comparison is available, and it is
misleading in a way worth spelling out, because the direction of the error is counterintuitive.
Within the credit union system, larger institutions generally grow faster. Over the study period the median non-rural credit
union under $10 million actually shrank, while those above $1 billion grew close to 5% a year. Growth scales with size.
Rural credit unions are concentrated at the small end of that distribution. Comparing them to the average non-rural credit
union therefore compares them to institutions that are systematically larger — and therefore systematically faster-growing
for reasons having nothing to do with geography. The straightforward comparison does not flatter rural credit unions. It
penalises them.
This matters for how the results below should be read. When we adjust for size, the rural advantage does not shrink toward
zero as one might expect of a spurious finding. It grows. That pattern — where controlling for a variable strengthens rather
than weakens a relationship — is the signature of a suppressor, and it is the first indication that "rural" and "small" are not
the same thing.

Four separate approaches were used, deliberately chosen so that each rests on different assumptions. If all four agree, the
conclusion does not depend on any one of them being right.
A rule written in advance. Before any analysis was run, we recorded the decision rule: if the gap between rural and non-
  rural credit unions largely disappears once size is accounted for, we would conclude that scale is the operative factor and reorient the report accordingly. This matters. Given enough freedom, an analyst can nearly always find support for an
expected conclusion — not through dishonesty, but through the accumulation of small, individually defensible choices. Fixing
the rule beforehand removes that freedom.
Comparison within size brackets. Credit unions were sorted into six asset bands, from under $10 million to above $1
billion, and rural and non-rural institutions compared within each band. This involves no statistical model at all — no
assumption about the shape of the relationship between size and performance, no equation to specify. It simply asks
whether, among institutions of similar size, rural ones perform differently.
Statistical adjustment. A regression compared rural to non-rural credit unions while holding constant asset size (flexibly,
                                                                                                                  allowing the relationship to curve), institution age, charter type, low-income and minority designations, and accounting-
  standard changes, with separate allowances for every state in every quarter. This is the conventional approach and gives the
formal estimate.
Direct matching. Finally, each rural credit union was paired with the non-rural credit union closest to it in size in the same
quarter, keeping only pairs within 10% of one another on assets, and the difference within each pair averaged. This
produced 33,403 matched pairs. It is the most intuitive of the four — no model, no controls, no coefficients, simply like-for-
  like comparison.

A preliminary check deserves its own mention, because it is the one that determines whether the rest of the exercise means
anything.
Statistical adjustment can only compare institutions that actually resemble one another. If rural credit unions occupied a size
range that non-rural credit unions barely populated — if rural were all $5 million and non-rural all $500 million — then no
amount of adjustment would rescue the comparison. The procedure would be extrapolating into territory where it has no
data, and the resulting number would be an artifact of the equation rather than a fact about the world.
Ninety-nine percent of non-rural credit union observations fall inside the size range occupied by rural credit
unions. For essentially every rural institution in the data, there exist non-rural institutions of near-identical size available for
comparison. The matched-pairs exercise confirms this from the other side: nearly all rural credit unions found a non-rural
partner within 10% on assets.
This is not a technicality. It is the reason the comparison is legitimate.


Within size brackets
Comparing rural to non-rural credit unions of similar size, the rural advantage in asset growth appears in all six brackets,
ranging from 1.8 to 2.9 percentage points. It does not narrow as institutions get larger, which is what one would expect if
size were secretly doing the work. The advantage in return on assets likewise appears in all six brackets.
If "rural" were merely "small,
" these within-bracket comparisons should have shown nothing. Six separate comparisons, six
times the same answer.
Matched pairs
The matched-pairs result is the most direct statement available:
  Rural Matched non-rural Difference
Asset growth 4.11% 2.43% +1.68 pp
Return on assets 0.54% 0.31% +0.23 pp
Net worth ratio 13.44% 13.29% +0.16 pp
Each rural credit union here is compared to a non-rural credit union of almost identical size, in the same quarter. Rural
institutions grew assets roughly 70% faster and earned roughly 70% more on assets. On capital they were essentially indistinguishable.
Statistical adjustment
The regression tells the same story, and its internal pattern is informative:
  Specification Asset growth Return on assets
No adjustment 0.86 0.14
Adjusting for size 1.61 0.22
Adding institution characteristics 1.46 0.22
Adding state and time effects 1.03 0.17
Adjusting for size nearly doubles the estimated rural advantage in growth, confirming that the unadjusted comparison
understates it. Adding state and time effects then absorbs regional and cyclical variation, leaving a conditional estimate of
roughly one percentage point of additional annual asset growth and 0.17 percentage points of additional return on assets.
The two methods agree almost exactly. The matched-pairs estimate (1.68 for growth, 0.227 for return on assets) is nearly
identical to the size-adjusted regression (1.61 and 0.222). One approach imposes an equation; the other imposes nothing.
That they converge means the finding does not depend on how it was modelled — which is the property one most wants in a
result that will be scrutinised.

A result of this kind invites three specific objections. Each was tested.
"The weak ones failed, so the survivors look good.
" This is the most serious challenge. If struggling rural credit unions
disappeared faster than others, the institutions remaining would look strong for reasons unrelated to geography.
The evidence runs the other way. Over the study period 36.9% of rural credit unions ceased reporting, against 44.1% of non-
  rural ones. Adjusting for size, capital, profitability, and state, a rural credit union was roughly 25% less likely to disappear
than a comparable non-rural one. Rural institutions retained more of their weaker members than the rest of the system did
— and still outperformed.
As a further test, the comparison was repeated using only credit unions present continuously from 2010 to the present, a
group within which selection cannot operate at all. The rural advantage there is roughly four-fifths as large and remains
clearly present.
"It's an artifact of where charters are registered.
" Every measure above classifies a credit union by the county of its
headquarters. A metropolitan institution with rural branches, or a rural-headquartered institution lending entirely in a city,
would be misclassified.
Using the branch network instead — classifying an institution by where the majority of its offices actually are, drawn from
every quarterly branch file since 2010 — the two definitions agree for 98.8% of observations, and the estimated advantage is
materially unchanged (1.031 against 1.029 for asset growth). The finding does not depend on charter domicile.
"It's driven by a handful of institutions.
" All the within-bracket comparisons use medians rather than averages, so no
small number of unusual institutions can drive them. The matched-pairs result rests on 33,403 separate comparisons.

On one of the three outcomes the statute names, the answer is different.
Rural credit unions report higher capital ratios than the system as a whole. But most of that difference is a size effect:
  smaller institutions hold more capital relative to assets as a matter of course. Compared like-for-like, rural net worth is
13.44% against 13.29% — a difference of 0.16 percentage points on a base above 13, statistically detectable but
economically negligible. A formal decomposition attributes only about 31% of the apparent capital advantage to anything
other than observable characteristics, against roughly 150% for growth and profitability. Under the branch-network
definition, the capital difference is not statistically distinguishable from zero at all.

So on capital, and on capital alone,
"rural" really does substantially mean "small.
"
We then tested the obvious inference, and it did not hold. A credit union cannot issue stock; its capital comes from
retained earnings, and because supervisory requirements tie capital to assets, the rate at which an institution can
accumulate earnings sets a ceiling on how fast it can grow. Institutions growing fast with no capital advantage might
therefore be pressing against that ceiling.
They are not. Computing the ceiling for every institution — its return on assets relative to its capital ratio — the typical rural
credit union is growing at 4.0% against a sustainable rate of 6.8%, leaving 2.7 percentage points of headroom. The typical
non-rural one has 2.8 points. About a third of each group grows faster than retained earnings support, and that share is the
same for both. Splitting by low-income designation, which permits access to secondary capital, changes nothing: all four
groups show between 2.3 and 3.3 points of headroom.
This is a negative result, and a useful one. Capital relief is the natural remedy to propose for institutions that perform well
but hold thin capital. Rural credit unions are neither thinly capitalised relative to comparable peers nor constrained by
capital in their growth. A recommendation along those lines would address a problem this evidence does not show.
One distinction must be preserved. What has been tested is whether capital constrains existing rural credit unions. It does
not. Whether initial capital requirements deter the formation of new ones rests on a different mechanism — a new charter
needs capital before it has any earnings — and remains untested.

Established. Rural credit unions outperform comparable non-rural institutions on growth and profitability. The difference is
not an artifact of their smaller size, is not produced by the selective failure of weaker institutions, and is not an accident of
where charters are registered. Four methods resting on different assumptions produce the same answer, and two of them —
matched pairs and size-adjusted regression — agree to within a rounding error. On capital adequacy, by contrast, the
apparent rural advantage is largely a size effect and essentially disappears under like-for-like comparison.
Not established. We have shown that rural credit unions perform differently; we have not shown why.
"Rural" is not a
single characteristic. It bundles together less local competition, a different member base, different field-of-membership
structures, and a local economy with its own dynamics. Any of these could be doing the work. Identifying which is a separate
question, and the report should not imply otherwise.
Three further limits deserve statement. The rural population here is 765 institutions holding roughly 2.5% of system assets —
findings are statistically robust but the sector is small. Demographic decline sets a ceiling that no regulatory change can lift;
policy cannot make members appear in a county losing population. And roughly one rural credit union in seven changes
classification depending on which vintage of the federal rural definition is applied, with no change whatever in its business.

The pre-committed rule pointed to one of two paths. The gap did not disappear under adjustment; it strengthened. The
report therefore cannot be organised around remedying underperformance among rural credit unions, because on the
measures Congress specified there is little underperformance to remedy.
What the evidence supports instead is narrower and, we think, more useful. The institutions that exist perform well, persist
better than average, and have been expanding their office networks faster than non-rural ones. They are not constrained by
capital. What is not happening is formation: roughly one new rural credit union appears each year against fifteen departures,
and four-fifths of those departures appear to be mergers rather than failures.
The consolidation is occurring at the charter level, not at the level of service to communities. That is a materially different
diagnosis from the one the statute anticipates, and it points the inquiry at Sec. 909(c)(2)(b) — the formation of new charters
in rural areas — rather than at remedies for weak institutions.
